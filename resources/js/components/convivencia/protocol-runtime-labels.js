export function convivenciaProtocolRuntimeLabel(value, fallback = null) {
  if (value === null || value === undefined || value === "") return fallback;
  const original = String(value).trim();
  const normalized = normalizeProtocolToken(original);
  const exact = CONVIVENCIA_COMPLETION_CRITERIA_LABELS[normalized]
    || CONVIVENCIA_PROTOCOL_PART_CATEGORY_LABELS[normalized]
    || CONVIVENCIA_PROTOCOL_CONDITION_LABELS[normalized];
  if (exact) return exact;
  if (!original.includes("_") && !original.includes("-")) return fallback;

  const translated = normalized.split("_").map((token) => FALLBACK_PROTOCOL_TOKENS[token]);
  if (translated.every(Boolean)) {
    const sentence = translated.join(" ");
    return sentence.charAt(0).toLocaleUpperCase("es-CL") + sentence.slice(1);
  }

  return fallback;
}

export function convivenciaProtocolPartCategoryLabel(value, fallback = "Sin categoría") {
  if (value === null || value === undefined || value === "") return fallback;
  const original = String(value).trim();
  return CONVIVENCIA_PROTOCOL_PART_CATEGORY_LABELS[normalizeProtocolToken(original)]
    || convivenciaProtocolRuntimeLabel(original)
    || original;
}
